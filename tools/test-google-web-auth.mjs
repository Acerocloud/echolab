import assert from 'node:assert/strict';
import {createGoogleWebAuth, DRIVE_SCOPE} from '../js/google-web-auth.js';
let config, request, clock=100000, changes=[];
const auth=createGoogleWebAuth({clientId:'12345-abc123.apps.googleusercontent.com',now:()=>clock,onChange:value=>changes.push(value),load:async()=>({initTokenClient:c=>{config=c;return{requestAccessToken:o=>{request=o;}}}})});
await assert.rejects(auth.signIn(),/尚未准备好/);
await auth.prepare();
assert.equal(config.scope,DRIVE_SCOPE);
const logged=auth.signIn();assert.equal(request.prompt,'select_account');
config.callback({access_token:'test-token',expires_in:120,scope:DRIVE_SCOPE});await logged;
assert.equal(auth.currentToken(),'test-token');clock+=61000;assert.equal(auth.currentToken(),'');
assert.deepEqual(changes,[true,false]);
const cancelled=auth.signIn();config.error_callback({type:'popup_closed'});await assert.rejects(cancelled,/关闭/);
const noScope=auth.signIn();config.callback({access_token:'test-token',expires_in:120,scope:'openid'});await assert.rejects(noScope,/未授权/);
const blocked=auth.signIn();config.error_callback({type:'popup_failed_to_open'});await assert.rejects(blocked,/阻止/);
const disconnected=auth.signIn();auth.disconnect();await assert.rejects(disconnected,/取消/);assert.equal(auth.currentToken(),'');
await assert.rejects(createGoogleWebAuth({clientId:'bad'}).prepare(),/尚未配置/);
console.log('Google web OAuth: user gesture, scope, expiry, popup and disconnect verified');
