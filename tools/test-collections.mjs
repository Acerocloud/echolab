import assert from 'node:assert/strict';
globalThis.window = new EventTarget();
globalThis.localStorage = { getItem:()=>null, setItem:()=>{} };
const {state, usageKey, saveUsage, addPronunciation} = await import('../js/store.js');
const {toggleCollection} = await import('../js/collections.js');
const {learningSnapshot, validateSnapshot, applyLearningSnapshot} = await import('../js/cloud-records.js');
const {getKeys} = await import('../js/keys.js');
const item={word:'taking',lesson:'muse-launch',cue:2,en:'taking a break',zh:'休息'};
assert.equal(toggleCollection('words',item),true);
assert.equal(toggleCollection('usages',item),true);
assert.equal(toggleCollection('pronunciations',item),true);
assert.equal(state.words[0].en,item.en);
assert.equal(state.usages[0].en,item.en);
assert.equal(state.pronunciations[0].en,item.en);
assert.equal(addPronunciation({...item,word:'TAKING'}),false);
const key=usageKey(item.word,item.lesson,{i:item.cue,en:item.en});
state.usages[0].note='保留笔记';saveUsage({id:key,word:item.word,explanation:'解释'});
assert.equal(state.usages[0].note,'保留笔记');
assert.equal(toggleCollection('words',item),false);
assert.equal(state.usages.length,1);assert.equal(state.pronunciations.length,1);
const snapshot=learningSnapshot(state);assert.equal(snapshot.version,4);
const restored={};applyLearningSnapshot(restored,snapshot);assert.equal(restored.usages[0].note,'保留笔记');
assert.deepEqual(validateSnapshot({format:'echolab-learning',version:1,data:{words:[]}}).data.pronunciations,[]);
assert.deepEqual(validateSnapshot({format:'echolab-learning',version:3,data:{subtitleEdits:{}}}).data.pronunciations,[]);
state.settings.keys={repeat:'r',prev:'ArrowLeft',next:'ArrowRight',loop:'x'};
assert.deepEqual([getKeys().prev,getKeys().next,getKeys().repeat,getKeys().loop],['ArrowUp','ArrowDown','ArrowLeft','x']);
state.settings.keys={repeat:'q',prev:'a',next:'d'};
assert.deepEqual([getKeys().prev,getKeys().next,getKeys().repeat],['a','d','q']);
console.log('Collection cross-actions, old backups, sync protection and shortcuts verified');
